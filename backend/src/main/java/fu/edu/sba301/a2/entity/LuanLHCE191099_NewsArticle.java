package fu.edu.sba301.a2.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Nationalized;

// JPA mapping for the SQL Server NewsArticle table; this class represents persisted data.
// @Column names preserve the assignment schema, and @Nationalized maps text fields to Unicode SQL types.
// Lombok generates accessors and the empty constructor required by JPA.
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "NewsArticle")
public class LuanLHCE191099_NewsArticle {

    // Primary key generated by SQL Server IDENTITY; a new unsaved entity starts with a null ID.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "NewsArticleID")
    private Long id;

    @Nationalized
    @Column(name = "NewsTitle", nullable = false, length = 200)
    private String title;

    @Nationalized
    @Column(name = "Headline", length = 500)
    private String headline;

    @Column(name = "CreatedDate", nullable = false)
    private LocalDateTime createdDate;

    @Nationalized
    @Column(name = "NewsContent", nullable = false, length = 10000)
    private String content;

    @Nationalized
    @Column(name = "NewsSource", length = 255)
    private String source;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    // Required foreign key: every news article belongs to exactly one category.
    @JoinColumn(name = "CategoryID", nullable = false)
    private LuanLHCE191099_Category category;

    @Column(name = "NewsStatus", nullable = false)
    private Integer status;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    // Required author relation; multiple news articles may be created by the same Staff account.
    @JoinColumn(name = "CreatedByID", nullable = false)
    private LuanLHCE191099_Account createdBy;

    @ManyToOne(fetch = FetchType.LAZY)
    // Optional editor relation: a newly created article has not necessarily been edited yet.
    @JoinColumn(name = "UpdatedByID")
    private LuanLHCE191099_Account updatedBy;

    @Column(name = "ModifiedDate")
    private LocalDateTime modifiedDate;

    // An article owns its tags through NewsTag; unique TagID prevents one tag from belonging to two articles.
    // CascadeType.ALL propagates persistence/removal; orphanRemoval deletes tags removed from this collection.
    // No separate NewsTag Java entity is needed because the join table stores only these foreign keys.
    @OneToMany(cascade = CascadeType.ALL, orphanRemoval = true)
    @JoinTable(
        name = "NewsTag",
        joinColumns = @JoinColumn(name = "NewsArticleID"),
        inverseJoinColumns = @JoinColumn(name = "TagID"),
        uniqueConstraints = @UniqueConstraint(columnNames = "TagID")
    )
    private List<LuanLHCE191099_Tag> tags = new ArrayList<>();
}

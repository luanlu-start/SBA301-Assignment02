package fu.edu.sba301.a2.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Nationalized;

// JPA mapping for the SQL Server Category table; this class represents persisted data.
// @Column names preserve the assignment schema, and @Nationalized maps text fields to Unicode SQL types.
// Lombok generates accessors and the empty constructor required by JPA.
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "Category")
public class LuanLHCE191099_Category {

    // Primary key generated by SQL Server IDENTITY; a new unsaved entity starts with a null ID.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "CategoryID")
    private Long id;

    @Nationalized
    @Column(name = "CategoryName", nullable = false, length = 100)
    private String name;

    @Nationalized
    @Column(name = "CategoryDescription", length = 500)
    private String description;

    // Self-reference: many categories may share one parent category; null means there is no parent.
    // LAZY defers loading the related parent until it is accessed within the persistence context.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "ParentCategoryID")
    private LuanLHCE191099_Category parent;

    // The Java status property maps to IsActive in the database: 1 = Active and 0 = Inactive.
    @Column(name = "IsActive", nullable = false)
    private Integer status;
}

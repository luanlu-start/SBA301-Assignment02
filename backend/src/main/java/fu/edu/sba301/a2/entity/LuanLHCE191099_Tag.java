package fu.edu.sba301.a2.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Nationalized;

// JPA mapping for the SQL Server Tag table; this class represents persisted data.
// @Column names preserve the assignment schema, and @Nationalized maps text fields to Unicode SQL types.
// Lombok generates accessors and the empty constructor required by JPA.
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "Tag")
public class LuanLHCE191099_Tag {

    // Primary key generated by SQL Server IDENTITY; a new unsaved entity starts with a null ID.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "TagID")
    private Long id;

    @Nationalized
    @Column(name = "TagName", nullable = false, length = 50)
    private String name;

    @Nationalized
    @Column(name = "Note", length = 250)
    private String note;
}
